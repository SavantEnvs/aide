static void cleanup(void) {
    if (newdb_path[0]) unlink(newdb_path);
    if (conf_path[0]) unlink(conf_path);
    if (tmpdir[0]) rmdir(tmpdir);
}

static void write_file(const char *path, const char *data) {
    FILE *f = fopen(path, "w");
    if (!f || fputs(data, f) == EOF || fclose(f) != 0) {
        perror(path);
        exit(1);
    }
}

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "usage: %s <input file>\n", argv[0]);
        return 1;
    }
    char *args[16];
    int n = 0;
    args[n++] = "aide";

    if (AIDE_FUZZ_MODE == MODE_CONFIG) {
        args[n++] = "--config";
        args[n++] = argv[1];
        args[n++] = "--config-check";
    } else {
        char input[PATH_MAX];
        if (!realpath(argv[1], input)) {
            perror(argv[1]);
            return 1;
        }
        const char *t = getenv("TMPDIR");
        if (!t || !*t) t = "/tmp";
        snprintf(tmpdir, sizeof tmpdir, "%s/aide-fuzz-XXXXXX", t);
        if (!mkdtemp(tmpdir)) {
            perror("mkdtemp");
            return 1;
        }
        atexit(cleanup);
        snprintf(conf_path, sizeof conf_path, "%s/aide.conf", tmpdir);

        char conf[3 * PATH_MAX];
        if (AIDE_FUZZ_MODE == MODE_COMPARE) {
            snprintf(newdb_path, sizeof newdb_path, "%s/new.db", tmpdir);
            write_file(newdb_path, NEW_DB);
            snprintf(conf, sizeof conf,
                     "database_in=file:%s\n"
                     "database_new=file:%s\n"
                     "report_level=added_removed_entries\n"
                     "report_format=plain\n"
                     "report_url=stdout\n"
                     "report_format=json\n"
                     "report_url=stdout\n",
                     input, newdb_path);
        } else {
            snprintf(conf, sizeof conf, "database_in=file:%s\n", input);
        }
        write_file(conf_path, conf);
        args[n++] = "--config";
        args[n++] = conf_path;
        if (AIDE_FUZZ_MODE == MODE_COMPARE) {
            args[n++] = "--compare";
        } else {
            args[n++] = "--list";
            args[n++] = "--limit";
            args[n++] = "/e";
        }
    }
    args[n++] = "--no-progress";
    args[n++] = "--workers";
    args[n++] = "1";
    args[n] = NULL;
    return aide_original_main(n, args);
}
