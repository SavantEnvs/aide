/*
 * File-input fuzz driver for aide's own CLI (mayhem/build.sh links it against aide's
 * sanitized objects, with aide's main() renamed to aide_original_main by objcopy).
 *
 *   aide_compare <file>   <file> is the database_in of `aide --compare` (the new database
 *                         is a small fixed valid one), reports in plain AND json format.
 *   aide_list <file>      <file> is the database_in of `aide --list --limit /e`.
 *   aide_config <file>    <file> is the config of `aide --config-check`.
 *
 * The database path lives in aide's config, not argv, so for the two database modes this
 * driver writes a fixed config (and the fixed new database) into a fresh mkdtemp() directory
 * under $TMPDIR and removes it at exit. Nothing else is kept between inputs: every input is
 * a new process. aide exits non-zero for found differences / bad input; only signals and
 * sanitizer reports are findings.
 */
#include <limits.h>
