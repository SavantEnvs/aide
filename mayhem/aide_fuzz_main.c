#include <stdlib.h>
#include <string.h>
#include <unistd.h>

int aide_original_main(int argc, char **argv);

#define MODE_COMPARE 1
#define MODE_LIST 2
#define MODE_CONFIG 3

#ifndef AIDE_FUZZ_MODE
#error "build with -DAIDE_FUZZ_MODE=1|2|3"
#endif

